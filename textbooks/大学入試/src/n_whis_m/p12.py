    assert lv.count("A") == 4 and 4 <= lv.count("B") <= 5 and lv.count("C") == 2, lv
    assert lv == sorted(lv), lv
    for it in items:
        for k in ("lv", "tag", "q", "a", "s"):
            assert it.get(k, "").strip(), k
        assert "<b>ポイント</b>" in it["s"], it["q"][:20]
        assert "$" not in it["q"] + it["a"] + it["s"]
        assert "（　" not in it["a"] + it["s"]
        lim = [int(x) for x in re.findall(r"(\d+)字以内", it["q"])]
        ex = re.findall(r"解答例：(.*?)（(\d+)字）", it["a"])
        assert len(lim) == len(ex), (it["tag"], lim, ex)
        for L, (body, n) in zip(lim, ex):
            assert len(body) == int(n) and 0.75 * L <= len(body) <= L, (len(body), n, L)
        m = re.search(r"〔(.*?)〕", it["q"])
        if m:   # 指定語句がすべて解答例に入っていること
            for w in m.group(1).split("　"):
                assert w in it["a"], w
