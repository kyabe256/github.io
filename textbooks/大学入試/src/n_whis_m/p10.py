SEQCHK = [(6, None, {"Ⅰ": 1792.09, "Ⅱ": 1791.06, "Ⅲ": 1789.06})]
ONECHK = [(7, (1789, 1799), {"①": 1757, "②": 1840, "③": 1793, "④": 1858})]

def verify():
    import re
    no = 10
    d = CH[no]
    assert d["goal"].strip()
    items = d["items"]
    lv = [it["lv"] for it in items]
    assert lv.count("A") == 4 and 4 <= lv.count("B") <= 5 and lv.count("C") == 2, lv
    assert lv == sorted(lv), lv
    for it in items:
        for k in ("lv", "tag", "q", "a", "s"):
            assert it.get(k, "").strip(), k
        assert "<b>ポイント</b>" in it["s"], it["q"][:20]
        assert "$" not in it["q"] + it["a"] + it["s"]
        assert "（　" not in it["a"] + it["s"]
        lim = [int(x) for x in re.findall(r"(\d+)字以内", it["q"])]
        ex = re.findall(r"解答例：(.*?)（(\d+)字）", it["a"])
        assert len(lim) == len(ex), (it["tag"], lim, ex)
        for L, (body, n) in zip(lim, ex):
            assert len(body) == int(n) and 0.75 * L <= len(body) <= L, (len(body), n, L)
        m = re.search(r"〔(.*?)〕", it["q"])
        if m:   # 指定語句がすべて解答例に入っていること
            for w in m.group(1).split("　"):
                assert w in it["a"], w
    for i, tf in TFCHK.items():
        assert items[i]["tag"] == "正誤" and items[i]["a"].startswith(NUM[TFS.index(tf)]), i
    for i, lab, ys in SEQCHK:
        assert len(set(ys.values())) == 3
        order = "→".join(sorted(ys, key=ys.get))
        ans = NUM[ORD.index(order)] + "（" + order + "）"
        assert (items[i]["a"].startswith(ans) if lab is None else f"{lab} {ans}" in items[i]["a"]), (i, ans)
    for i, (lo, hi), ys in ONECHK:
        hit = [k for k, y in ys.items() if lo <= y <= hi]
        assert len(hit) == 1 and items[i]["a"].startswith(hit[0]), (i, hit)
    # C1(1)は指定語「労働力」を含むこと
    assert "労働力" in re.findall(r"解答例：(.*?)（", items[9]["a"])[0]
