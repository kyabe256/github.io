def verify():
    chk(CH)
    A = {"H": 1.0, "C": 12, "N": 14, "O": 16, "Cl": 35.5, "Br": 80, "Ca": 40, "Na": 23}
    # A2
    assert mw("C8H8", A) == 104 and 5.2e4 / 104 == 500 and sf(2.8e5 / mw("C2H4", A)) == 1.0e4
    assert mw("C2H3Cl", A) == 62.5 and 6.25e4 / 62.5 == 1000
    # B1
    eq("C6H10O4 + C6H16N2 -> C12H22N2O2 + 2H2O")
    u = mw("C12H22N2O2", A); assert u == 226 and 4.52e4 / u == 200
    assert mw("C6H10O4", A) == 146 and sf(1000 / u * 146, 3) == 646
    eq("C6H8O2Cl2 + C6H16N2 -> C12H22N2O2 + 2HCl")
    # B2
    eq("C3H6O3 -> C3H4O2 + H2O")
    assert mw("C3H4O2", A) == 72 and sf(1000 / 72 * mw("C3H6O3", A) / 1000, 3) == 1.25 and 1.44e5 / 72 == 2000
    # B3
    eq("2RSO3H + Ca{2+} -> (RSO3)2Ca + 2H{+}".replace("R", "C"))   # R を C として原子数を点検
    h = 0.0200 * 0.0125; assert sf(h, 3) == 2.50e-4 and sf(h / 2 / 0.0500, 3) == 2.50e-3
    # B5
    nb = 1.81 / 160; assert sf(nb, 3) == 1.13e-2 and sf(nb * 54, 3) == 0.611
