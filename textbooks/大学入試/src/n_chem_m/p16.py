    assert sf(ms, 3) == 0.389 and sf(ns, 3) == 3.74e-3 and round(nb / ns) == 3 and sf(nb / ns, 3) == 3.02 and round(ms * 100) == 39
    # C1
    M = 1.00 * 8.31e3 * 300 / (2.40e2 * 0.100); assert sf(M, 3) == 1.04e5 and sf(1.04e5 / 104) == 1.0e3
