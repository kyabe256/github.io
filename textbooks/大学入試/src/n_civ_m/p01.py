    fills = ["#e9e4f6", "#ddd6f0", "#d0c7ea", "#c3b8e3", "#b6a9dd"]
    out = []
    for k in range(5):
        y0, y1 = top + 40 * k, top + 40 * (k + 1)
        pts = [(ax - hw(y0), y0), (ax + hw(y0), y0), (ax + hw(y1), y1), (ax - hw(y1), y1)]
        if k == 0:
            pts = pts[:1] + pts[2:]
        out.append('<polygon points="%s" fill="%s" stroke="#4b3f7a" stroke-width="1"/>'
                   % (" ".join("%g,%g" % p for p in pts), fills[k]))
        ym = (y0 + y1) / 2
        out.append('<line x1="%g" y1="%g" x2="262" y2="%g" stroke="#888" stroke-width="0.8" stroke-dasharray="3,2"/>'
                   % (ax + hw(ym) + 2, ym, ym))
        out.append('<text x="268" y="%g" font-size="11">%s</text>' % (ym + 4, labels[k]))
    out.append('<text x="130" y="228" font-size="10" text-anchor="middle">（下の段ほど基礎的な欲求）</text>')
    return '<svg class="fig" width="420" height="236" viewBox="0 0 420 236">' + "".join(out) + "</svg>"


