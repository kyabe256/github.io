def tf_combos(n):
    return list(product("正誤", repeat=n))


def TFQ(sts, labs="abc"):  # 2文・3文の正誤の組合せ
    n = len(sts)
    body = B("<br>".join(f"{labs[i]}　{t}" for i, (t, _) in enumerate(sts)))
    cells = [f"{MARU[i]} " + "　".join(f"{labs[j]} {c[j]}" for j in range(n)) for i, c in enumerate(tf_combos(n))]
    return body + "<br>".join("　　".join(cells[i:i + 4]) for i in range(0, len(cells), 4))


def tf_ans(sts):
    return MARU[tf_combos(len(sts)).index(tuple("正" if f else "誤" for _, f in sts))]


def PQ(names, labs="アイウ"):  # 3つの記述と人物の組合せ（6通り）
    cells = [f"{MARU[i]} " + "　".join(f"{labs[j]} {p[j]}" for j in range(len(labs)))
             for i, p in enumerate(permutations(names))]
    return "<br>".join("　　".join(cells[i:i + 2]) for i in range(0, len(cells), 2))


def perm_ans(names, correct, labs="アイウ"):
    return MARU[list(permutations(names)).index(tuple(correct[l] for l in labs))]


def pick(xs, want=True):  # 「適当なもの」は want=True、「誤っているもの」は want=False
    hit = [i for i, (_, f) in enumerate(xs) if f == want]
    assert len(hit) == 1, hit
    return MARU[hit[0]]


