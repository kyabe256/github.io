            assert t.count("$") % 2 == 0, (NO, i, k)
            for tg in ("div", "table", "tr", "td", "th", "b", "u", "span", "svg", "sub", "sup"):
                assert len(re.findall(f"<{tg}[ >]", t)) == t.count(f"</{tg}>"), (NO, i, k, tg)
