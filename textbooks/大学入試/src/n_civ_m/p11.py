def _svg(w, h, body):
    return f'<svg class="fig" width="{w}" height="{h}" viewBox="0 0 {w} {h}">' + "".join(body) + "</svg>"


def _t(x, y, s, size=11, anchor="middle", col="#222"):
    return f'<text x="{x:.1f}" y="{y:.1f}" font-size="{size}" text-anchor="{anchor}" fill="{col}">{s}</text>'


def _ln(x1, y1, x2, y2, w=1.0, dash="", col="#222"):
    d = f' stroke-dasharray="{dash}"' if dash else ""
    return f'<line x1="{x1:.1f}" y1="{y1:.1f}" x2="{x2:.1f}" y2="{y2:.1f}" stroke="{col}" stroke-width="{w}"{d}/>'


def _poly(pts, fill, op=1.0):
    return '<polygon points="' + " ".join(f"{x:.1f},{y:.1f}" for x, y in pts) + f'" fill="{fill}" fill-opacity="{op}" stroke="none"/>'


def _dot(x, y, r=2.6):
    return f'<circle cx="{x:.1f}" cy="{y:.1f}" r="{r}" fill="#222"/>'


def _arrow(x1, y1, x2, y2, w=1.1, col="#222", hs=6.0):
    from math import atan2, cos, sin
    a = atan2(y2 - y1, x2 - x1)
    bx, by = x2 - hs * cos(a), y2 - hs * sin(a)
    px, py = 0.42 * hs * sin(a), -0.42 * hs * cos(a)
    return (_ln(x1, y1, bx, by, w, col=col) +
            f'<polygon points="{x2:.1f},{y2:.1f} {bx+px:.1f},{by+py:.1f} {bx-px:.1f},{by-py:.1f}" fill="{col}"/>')


I = lambda s: f'<tspan font-family="Liberation Serif,serif" font-style="italic" font-size="12.5">{s}</tspan>'


class Plot:
    """価格 P = a + b Q の直線を描く座標系"""
    def __init__(self, qmax, pmax, w=250, h=190, ox=46, oy=None):
        self.ox, self.oy = ox, (oy if oy is not None else h + 30)
        self.sx, self.sy = w / qmax, h / pmax
        self.qmax, self.pmax, self.w, self.h = qmax, pmax, w, h
        self.b = [_arrow(self.ox, self.oy, self.ox + w + 18, self.oy), _arrow(self.ox, self.oy, self.ox, self.oy - h - 14),
                  _t(self.ox + w + 22, self.oy + 4, "数量 " + I("Q"), 11, "start"),
                  _t(self.ox - 6, self.oy - h - 20, "価格 " + I("P"), 11, "start"),
                  _t(self.ox - 5, self.oy + 13, "O", 10, "end")]

    def X(self, q):
        return float(self.ox + self.sx * float(q))

    def Y(self, p):
        return float(self.oy - self.sy * float(p))

    def line(self, a, b, q1, q2, label, dq=4, dp=0, col="#1d4e89", w=1.7, anchor="start"):
        self.b.append(_ln(self.X(q1), self.Y(a + b * q1), self.X(q2), self.Y(a + b * q2), w, "", col))
        self.b.append(_t(self.X(q2) + dq, self.Y(a + b * q2) + dp, label, 11, anchor, col))

    def ptick(self, p, lab=None):
        self.b.append(_t(self.ox - 4, self.Y(p) + 4, lab if lab else str(p), 10, "end"))

    def qtick(self, q, lab=None):
        self.b.append(_t(self.X(q), self.oy + 13, lab if lab else str(q), 10))

    def guide(self, q, p):
        self.b.append(_ln(self.X(q), self.Y(p), self.X(q), self.oy, 0.8, "3,2", "#666"))
        self.b.append(_ln(self.X(q), self.Y(p), self.ox, self.Y(p), 0.8, "3,2", "#666"))

    def svg(self, extra_w=75):
        return _svg(int(self.ox + self.w + max(extra_w, 75)), int(self.oy + 22), self.b)


