def SH(s, src):  # 史料（原典の引用）
    return f'<div class="shiryo">{s}<div style="text-align:right;font-size:9pt">（{src}）</div></div>'


def TB(head, rows, cls="l w"):
    h = "<tr>" + "".join(f"<th>{c}</th>" for c in head) + "</tr>"
    r = "".join("<tr>" + "".join(f"<td>{c}</td>" for c in row) + "</tr>" for row in rows)
    return f'<table class="{cls}">{h}{r}</table>'


def OPT(*xs):  # 選択肢（1行に1つ）
    return "<br>".join(MARU[i] + " " + x for i, x in enumerate(xs))


