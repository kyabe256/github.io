def SEQ(ev):  # 年代整序（3つの出来事）
    return (B("<br>".join(f"{k}　{t}" for k, (t, _) in ev.items()))
            + "　".join(f"{MARU[i]} {o}" for i, o in enumerate(SEQ_ORD)))


def seq_ans(ev):
    o = "→".join(sorted(ev, key=lambda k: ev[k][1]))
    return MARU[SEQ_ORD.index(o)] + "（" + o + "）"


