    assert AUX["II"][0] < AUX["II"][1] and AUX["III"][0] == AUX["III"][1]
    # 12-11 グラフの値：最適濃度と、水平に置いたときの上側・下側
    r, s = dict(ROOT), dict(STEM)
    assert max(ROOT, key=lambda p: p[1])[0] == -10 and max(STEM, key=lambda p: p[1])[0] == -5
    assert s[-6] > 0 and r[-6] < 0
    assert s[-6] > s[-7] and r[-10] > r[-9] > 0      # 茎は下側、根は上側がよく伸びる
    sp = _spline(STEM)
    assert all(abs(y - dict(sp).get(x, y)) < 1e-9 for x, y in STEM)
