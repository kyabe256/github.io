def _maxdark(segs):
    """連続した暗期の最長（時間）。24時間の周期がくり返されるので、末尾と先頭の暗期はつながる。"""
    runs, cur = [], 0.0
    for a, b, k in segs + segs:          # 2日分並べてつなぎ目も数える
        if k == "D":
            cur += b - a
        elif k in ("L", "F"):
            if cur:
                runs.append(cur)
            cur = 0.0
    runs.append(cur)
    return min(max(runs), 24)


