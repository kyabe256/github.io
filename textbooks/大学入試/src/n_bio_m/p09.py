def _prim(u):
    """一次応答：抗体量の log10（u は注射後の日数）。潜伏期 4 日、12 日目に 100 倍で最大。"""
    if u < 4:
        return 0.0
    if u < 12:
        return 2.0 * (1 - _m.cos(_m.pi * (u - 4) / 8)) / 2
    return 2.0 - 0.7 * (1 - _m.exp(-(u - 12) / 6))


def _lgA(t):
    """抗A抗体の log10。28 日目の再注射後、2 日で増え始め 35 日目に 10^3.7 で最大（二次応答）。"""
    if t <= 30:
        return _prim(t)
    b0 = _prim(30)
    if t < 35:
        return b0 + (3.7 - b0) * (1 - _m.cos(_m.pi * (t - 30) / 5)) / 2
    return 3.7 - 0.6 * (1 - _m.exp(-(t - 35) / 8))


def _lgB(t):
    return _prim(t - 28) if t >= 28 else 0.0


