def _ap(t):
    """膜電位（mV）。1.0 ms に刺激、1.75 ms に +40 mV、2.75 ms に −80 mV、その後 −70 mV へ戻る。"""
    if t < 1.0:
        return -70.0
    if t < 1.25:
        return -70 + 15 * (t - 1.0) / 0.25
    if t < 1.75:
        return -55 + 95 * (1 - _m.cos(_m.pi * (t - 1.25) / 0.5)) / 2
    if t < 2.75:
        return 40 - 120 * (1 - _m.cos(_m.pi * (t - 1.75) / 1.0)) / 2
    return -70 - 10 * _m.exp(-(t - 2.75) / 0.8)


