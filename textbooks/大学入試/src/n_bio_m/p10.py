# ---------------- 図・表の小道具（各章ファイルに同じものを入れる） ----------------
def _svg(w, h, body):
    return f'<svg class="fig" width="{w}" height="{h}" viewBox="0 0 {w} {h}">' + "".join(body) + "</svg>"

def _t(x, y, s, size=10, anchor="middle", col="#222"):
    return f'<text x="{x:.1f}" y="{y:.1f}" font-size="{size}" text-anchor="{anchor}" fill="{col}">{s}</text>'

def _ln(x1, y1, x2, y2, w=1.0, col="#222", dash=""):
    d = f' stroke-dasharray="{dash}"' if dash else ""
    return f'<line x1="{x1:.1f}" y1="{y1:.1f}" x2="{x2:.1f}" y2="{y2:.1f}" stroke="{col}" stroke-width="{w}"{d}/>'

def _pl(pts, w=1.6, col="#1d4e89", dash=""):
    d = f' stroke-dasharray="{dash}"' if dash else ""
    return ('<polyline points="' + " ".join(f"{x:.1f},{y:.1f}" for x, y in pts) +
            f'" fill="none" stroke="{col}" stroke-width="{w}" stroke-linejoin="round"{d}/>')

def _dot(x, y, r=2.4, col="#222"):
    return f'<circle cx="{x:.1f}" cy="{y:.1f}" r="{r}" fill="{col}"/>'

def _arrow(x1, y1, x2, y2, w=1.1, col="#222", hs=6.0):
    a = _m.atan2(y2 - y1, x2 - x1)
    bx, by = x2 - hs * _m.cos(a), y2 - hs * _m.sin(a)
    px, py = 0.42 * hs * _m.sin(a), -0.42 * hs * _m.cos(a)
    return (_ln(x1, y1, bx, by, w, col) +
            f'<polygon points="{x2:.1f},{y2:.1f} {bx+px:.1f},{by+py:.1f} {bx-px:.1f},{by-py:.1f}" fill="{col}"/>')

def chart(series, xr, yr, xt, yt, xl, yl, w=340, h=210, logx=False, logy=False, ml=48, mb=34, extra=None):
    """series: [{pts, col, w, dash, lab, lx, ly, anc, mk}]、xt/yt: [(値, ラベル)]。座標は値で与える。"""
    L, R, T, Bm = ml, 14, 24, mb
    fx = _m.log10 if logx else (lambda v: v)
    fy = _m.log10 if logy else (lambda v: v)
    X = lambda v: L + (fx(v) - fx(xr[0])) / (fx(xr[1]) - fx(xr[0])) * (w - L - R)
    Y = lambda v: h - Bm - (fy(v) - fy(yr[0])) / (fy(yr[1]) - fy(yr[0])) * (h - Bm - T)
    b = []
    for v, lab in yt:
        b.append(_ln(L, Y(v), w - R, Y(v), 0.5, "#c8c8c8", "2,2"))
        b.append(_t(L - 4, Y(v) + 3.5, lab, 9.5, "end"))
    for v, lab in xt:
        b.append(_ln(X(v), h - Bm, X(v), h - Bm + 3, 0.9))
        b.append(_t(X(v), h - Bm + 13, lab, 9.5))
    b.append(_arrow(L, h - Bm, w - R + 8, h - Bm, 1.1, "#444", 5))
    b.append(_arrow(L, h - Bm, L, T - 12, 1.1, "#444", 5))
    b.append(_t(w - R + 8, h - 6, xl, 10, "end"))
    b.append(_t(L + 6, T - 10, yl, 10, "start"))
    if extra:
        b += extra(X, Y)
    for s in series:
        pts = [(X(x), Y(y)) for x, y in s["pts"]]
        b.append(_pl(pts, s.get("w", 1.6), s.get("col", "#1d4e89"), s.get("dash", "")))
        if s.get("mk"):
            b += [_dot(x, y, 2.3, s.get("col", "#1d4e89")) for x, y in pts]
        if s.get("lab"):
            b.append(_t(X(s["lx"]), Y(s["ly"]), s["lab"], 10, s.get("anc", "start"), s.get("col", "#1d4e89")))
    return _svg(w, h, b)

def B(s):
    return f'<div class="bun">{s}</div>'

def TB(head, rows, cls=""):
    h = "".join(f"<th>{c}</th>" for c in head)
    r = "".join("<tr>" + "".join(f"<td>{c}</td>" for c in row) + "</tr>" for row in rows)
    c = f' class="{cls}"' if cls else ""
    return f"<table{c}><tr>{h}</tr>{r}</table>"

def _check_items(ch, items, nb=(4, 5)):
    """形式の点検：lv の数、空欄、ポイント、論述の字数（問題文の「N字以内」と解答例の対応）。"""
    lv = [it["lv"] for it in items]
    assert lv.count("A") == 4 and nb[0] <= lv.count("B") <= nb[1] and lv.count("C") == 2, (ch, lv)
    assert lv == sorted(lv), (ch, lv)
    for i, it in enumerate(items, 1):
        for k in ("lv", "tag", "q", "a", "s"):
            assert it.get(k), (ch, i, k)
        assert "<b>ポイント</b>：" in it["s"], (ch, i)
        assert "$" not in it["q"] + it["a"] + it["s"], (ch, i)
        assert "（　）" not in it["a"], (ch, i)
        for k in ("q", "a", "s"):          # HTML のタグの対応
            for tg in ("div", "table", "tr", "td", "th", "svg", "sub", "sup", "b", "span", "u", "i"):
                assert len(_re.findall(f"<{tg}[ >]", it[k])) == it[k].count(f"</{tg}>"), (ch, i, k, tg)
        lims = [int(v) for v in _re.findall(r"(\d+)字以内", it["q"])]
        ans = _re.findall(r"解答例：(.*?)（(\d+)字）", it["a"])
        assert len(lims) == len(ans), (ch, i, lims, len(ans))
        for (txt, n), lim in zip(ans, lims):
            L = len(_re.sub(r"<[^>]+>", "", txt))
            assert L == int(n), (ch, i, "字数の表示が違う", L, n)
            assert 0.7 * lim <= L <= lim, (ch, i, "字数", L, lim)


