# 10-7 サルコメアの長さと張力：ミオシン 1.6 μm、アクチン（片側）1.0 μm、頭部のない中央部 0.2 μm
MYO, ACT, BARE = F(16, 10), F(1), F(2, 10)


def _tension(L):
    """L ≥ 2.0 μm の範囲の張力（最大＝100%）。重なりの長さに比例するとみなす。"""
    L = F(L)
    tip = L / 2 - ACT                       # アクチンの先端からサルコメア中央までの距離
    head = (MYO - BARE) / 2                 # 片側の頭部の部分の長さ
    ov = max(F(0), min(head, MYO / 2 - max(tip, BARE / 2)))
    return ov / head * 100


