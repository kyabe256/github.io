def _dark(t):
    """暗順応：感じることのできる最も弱い光の強さ（log10）。錐体と桿体の小さいほうで決まる。"""
    cone = 3 + 1.5 * _m.exp(-t / 2.5)
    rod = 0.5 + 11.4 * _m.exp(-t / 6)
    return min(cone, rod)


def _kink():
    t = 0.0
    while 3 + 1.5 * _m.exp(-t / 2.5) < 0.5 + 11.4 * _m.exp(-t / 6):
        t += 0.01
    return t


def _fig_dark():
    ts = [i * 0.1 for i in range(0, 401)]
