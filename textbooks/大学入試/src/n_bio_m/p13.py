def _co2(t):
    """北半球のある地点の大気中CO2濃度（模式、ppm）。t は観測開始（1月1日）からの年数。"""
    p = t - 0.37
    return 400 + 2.4 * t + 3.0 * _m.cos(2 * _m.pi * p) + 1.1 * _m.cos(4 * _m.pi * p - 0.2)


