def _rep(mols, new):
    out = []
    for a, b in mols:
        out += [(a, new), (b, new)]
    return out


def _band(m):
    return {"HH": "重", "HL": "中間", "LH": "中間", "LL": "軽"}["".join(m)]


def _ratio(mols):
    from collections import Counter
    return Counter(_band(m) for m in mols)


