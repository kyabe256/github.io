def _seeds(mother, father):
    """自家受粉・交配でできる種子（胚、胚乳、種皮）の一覧。胚のうの核はすべて同じ遺伝子型。"""
    out = []
    for e in mother:          # 卵細胞・極核の遺伝子（胚のう細胞 1 個に由来するので同じ）
        for s in father:      # 精細胞（2 個は同じ遺伝子）
            emb = "".join(sorted(e + s))
            endo = "".join(sorted(e + e + s))
            out.append((emb, endo, "".join(sorted(mother))))
    return out


