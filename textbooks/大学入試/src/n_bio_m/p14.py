COMP = dict(r1=0.6, K1=100, r2=0.7, K2=80, a12=0.5, a21=1.15)


def _comp(T=24, dt=0.01):
    n1 = n2 = 2.0
    out = []
    for i in range(int(round(T / dt)) + 1):
        out.append((i * dt, n1, n2))
        d1 = COMP["r1"] * n1 * (1 - (n1 + COMP["a12"] * n2) / COMP["K1"])
        d2 = COMP["r2"] * n2 * (1 - (n2 + COMP["a21"] * n1) / COMP["K2"])
        n1, n2 = n1 + d1 * dt, n2 + d2 * dt
    return out


