def _pcr(n):
    """長いゲノム DNA（2本鎖1分子）から n サイクル後の、目的の長さだけの2本鎖の数を、鎖の端の状態で数える"""
    # 2本鎖の分子 = (上の鎖の端, 下の鎖の端)。端は (左端がそろっているか, 右端がそろっているか)
    from collections import Counter
    mols = Counter({((False, False), (False, False)): 1})
    for _ in range(n):
        new = Counter()
        for (tp, bt), c in mols.items():
            new[(tp, (tp[0], True))] += c     # 上の鎖を鋳型に、右端のプライマーから左へ伸びる下の鎖
            new[((True, bt[1]), bt)] += c     # 下の鎖を鋳型に、左端のプライマーから右へ伸びる上の鎖
        mols = new
    assert sum(mols.values()) == 2 ** n
    return mols[((True, True), (True, True))]


