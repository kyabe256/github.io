# 1-10 Na+ の流出速度（相対値）の時間変化
def _na(t):
    if t <= 60:
        return 100
    if t <= 120:
        return 15 + 85 * math.exp(-(t - 60) / 8)
    if t <= 124:
        return 15 + 55 * (t - 120) / 4
    if t <= 180:
        return 15 + 55 * math.exp(-(t - 124) / 12)
    return 100 - 85 * math.exp(-(t - 180) / 8)


