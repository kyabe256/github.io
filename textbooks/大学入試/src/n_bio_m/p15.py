def _d(x, y):
    return DIFF.get((x, y), DIFF.get((y, x)))


def _upgma():
    """平均距離法で順にまとめる。結果：[(まとめた2群, その距離)]"""
    cl = {s: [s] for s in SP}
    steps = []
    while len(cl) > 1:
        ks = sorted(cl)
        best = None
        for i in range(len(ks)):
            for j in range(i + 1, len(ks)):
                a, b = ks[i], ks[j]
                dd = F(sum(_d(x, y) for x in cl[a] for y in cl[b]), len(cl[a]) * len(cl[b]))
                if best is None or dd < best[0]:
                    best = (dd, a, b)
        dd, a, b = best
        steps.append(((a, b), dd))
        cl[a + b] = cl.pop(a) + cl.pop(b)
    return steps


