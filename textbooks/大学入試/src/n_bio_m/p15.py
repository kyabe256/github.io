    assert RATE == 5 and F(_d("A", "B"), 2 * RATE) == F(8, 10) and F(_d("A", "C"), 2 * RATE) == F(16, 10)
    # 15-9 交配の割合
    tot = sum(MATE.values()); same = MATE[("S", "S")] + MATE[("M", "M")]
    assert (tot, same) == (60, 43) and round(same / tot * 100) == 72
    # 15-10 ヘテロ接合体の有利
    p0 = 1 - Q0
    assert (p0 * p0, 2 * p0 * Q0, Q0 * Q0) == (F(81, 100), F(18, 100), F(1, 100))
    q1 = _hw_next(Q0, SURV)
    assert q1 == F(92, 911) and round(float(q1), 3) == 0.101
