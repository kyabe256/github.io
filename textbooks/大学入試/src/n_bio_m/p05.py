def _tr(m, stop=True):
    out = []
    for i in range(0, len(m) - 2, 3):
        a = CODE[m[i:i + 3]]
        if a == "*" and stop:
            break
        out.append(a)
    return "".join(out)


def _ctab(cods, ncol=4):
    cells = [f"{c}：{JA[CODE[c]]}" + ("（開始）" if c == "AUG" else "") for c in cods]
    rows = [cells[i:i + ncol] + [""] * (ncol - len(cells[i:i + ncol])) for i in range(0, len(cells), ncol)]
    return '<table class="w">' + "".join("<tr>" + "".join(f"<td>{x}</td>" for x in r) + "</tr>" for r in rows) + "</table>"


def _rc(s):   # DNA 鋳型（3′→5′ で書いたもの）→ mRNA（5′→3′）
    return s.translate(str.maketrans("ATGC", "UACG"))


