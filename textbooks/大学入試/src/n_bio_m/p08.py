# 8-9 酸素解離曲線（ヒルの式）：CO2 40 mmHg で S(100)=0.96、CO2 60 mmHg で S(30)=0.30 となるよう P50 を決める
NH = 2.7
P50_40 = 100 / (0.96 / 0.04) ** (1 / NH)
P50_60 = 30 / (0.30 / 0.70) ** (1 / NH)


def _S(P, P50):
    return P ** NH / (P ** NH + P50 ** NH)


