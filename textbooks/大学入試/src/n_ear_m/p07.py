def _wind_from(ang):
    """北半球の地上の低気圧のまわり：反時計回りに、中心へ約 30° 吹きこむ。風が吹いてくる方位を返す"""
    flow = math.radians(ang + 90 + 30)                 # 流れていく向き（数学の向き）
    frm = (math.degrees(flow) + 180) % 360             # 吹いてくる向き（数学の向き）
    az = (90 - frm) % 360                              # 北から時計回り
    names = ["北", "北東", "東", "南東", "南", "南西", "西", "北西"]
    return names[int((az + 22.5) // 45) % 8]


