def _front(fr, n=30):
    th0, bend, L = fr
    out = []
    for i in range(n + 1):
        t = i / n
        a = math.radians(th0) + bend * t * (1 if fr is WF else -1)
        out.append((LC[0] + L * t * math.cos(a), LC[1] - L * t * math.sin(a)))
    return out


def _front_angle(fr, r):
    th0, bend, L = fr
    t = min(r / L, 1)
    return th0 + math.degrees(bend * t) * (1 if fr is WF else -1)


