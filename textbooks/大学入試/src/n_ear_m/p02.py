STRIPE = [(20, 80), (45, 180), (65, 260)]
EDGE = 80


def _fig_stripe():
    s, cx, y0, hh = 2.0, 180, 30, 56
    p = []
    bounds = [0] + [d for d, _ in STRIPE] + [EDGE]
    for i in range(len(bounds) - 1):
        col = "#444" if i % 2 == 0 else "#fff"
        for sg in (1, -1):
            xa, xb = cx + sg * s * bounds[i], cx + sg * s * bounds[i + 1]
            p.append(f'<rect x="{min(xa, xb):.1f}" y="{y0}" width="{abs(xb - xa):.1f}" height="{hh}" fill="{col}" stroke="#444" stroke-width="0.8"/>')
    p.append(_ln(cx, y0 - 12, cx, y0 + hh + 6, "#c0392b", 1.6, "4,3"))
    p.append(_tx(cx, y0 - 16, "海嶺軸", 10, "middle", "#c0392b"))
    for (d, _), lab in zip(STRIPE, "abc"):
        for sg in (1, -1):
            p.append(_tx(cx + sg * s * d, y0 - 4, lab, 11, "middle", it=True))
    for d in [0] + [d for d, _ in STRIPE] + [EDGE]:
        for sg in ((1, -1) if d else (1,)):
            p.append(_ln(cx + sg * s * d, y0 + hh, cx + sg * s * d, y0 + hh + 4, "#333", 1))
            p.append(_tx(cx + sg * s * d, y0 + hh + 15, str(d), 10, "middle"))
    p.append(_tx(cx, y0 + hh + 29, "海嶺軸からの距離 [km]", 10, "middle"))
    return _svg(360, 122, p)


