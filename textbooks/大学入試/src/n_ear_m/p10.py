def _ms(logT):            # 主系列の中心線（log L）
    return 6.8 * (logT - math.log10(TSUN))


def _fig_hr():
    ox, oy, w, h = 56, 24, 270, 220
    lt1, lt2 = math.log10(40000), math.log10(2500)
    X = lambda T: ox + w * (lt1 - math.log10(T)) / (lt1 - lt2)
    Y = lambda L: oy + h * (6 - math.log10(L)) / 10
    p = [f'<rect x="{ox}" y="{oy}" width="{w}" height="{h}" fill="#fff" stroke="#999" stroke-width="0.8"/>']
    for e in range(-4, 7, 2):
        p.append(_ln(ox, Y(10 ** e), ox + w, Y(10 ** e), "#eee", 0.8))
        p.append(_tx(ox - 4, Y(10 ** e) + 4, f"10<tspan dy='-4' font-size='8'>{e}</tspan>" if e not in (0,) else "1", 10, "end"))
    for T in (30000, 20000, 10000, 6000, 4000, 3000):
        p.append(_ln(X(T), oy, X(T), oy + h, "#eee", 0.8))
        p.append(_tx(X(T), oy + h + 13, str(T), 9, "middle"))
    band_hi, band_lo = [], []
    for i in range(0, 41):
        lt = lt1 + (lt2 - lt1) * i / 40
        T = 10 ** lt
        band_hi.append((X(T), Y(10 ** min(6, _ms(lt) + 0.5))))
        band_lo.append((X(T), Y(10 ** max(-4, _ms(lt) - 0.5))))
    p.append(f'<polygon points="{_pts(band_hi + band_lo[::-1])}" fill="#f7e3c4" stroke="none"/>')
    for k, T in (("O", 35000), ("B", 18000), ("A", 8700), ("F", 6750), ("G", 5600), ("K", 4450), ("M", 3100)):
        p.append(_tx(X(T), oy - 6, k, 10, "middle", "#7a4a1f"))
    for name, (T, L) in STARS.items():
        p.append(f'<circle cx="{X(T):.1f}" cy="{Y(L):.1f}" r="4" fill="{"#f5b400" if name == "太陽" else "#222"}" stroke="#222"/>')
        p.append(_tx(X(T) + 7, Y(L) + 4, name, 10))
    p += [_tx(ox + w / 2, oy + h + 27, "表面温度 [K]（左ほど高温）", 10, "middle"),
          _tx(14, oy + h / 2 - 8, "光度", 10, "middle"), _tx(14, oy + h / 2 + 6, "（太陽", 9, "middle"), _tx(14, oy + h / 2 + 18, "＝1）", 9, "middle"),
          _tx(ox + w - 4, oy + 14, "スペクトル型は上の文字", 8, "end", "#7a4a1f")]
    return _svg(340, 280, p)


