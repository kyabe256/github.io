SAMPLES = [3.2, 5.6, 6.9, 6.1, 3.8, 1.4, 0.3, 1.7]


def fig_wave(v=SAMPLES):
    """標本点を通るなめらかな曲線（Catmull-Rom 曲線）と、量子化の目盛り"""
    W, H, x0, x1, y0, y1 = 330, 200, 40, 316, 14, 168
    n = len(v)
    X = lambda t: x0 + (t + 0.5) / n * (x1 - x0)
    Y = lambda u: y1 - u / 7.5 * (y1 - y0)
    o = [f'<svg class="fig" width="{W}" height="{H}" viewBox="0 0 {W} {H}" xmlns="http://www.w3.org/2000/svg" font-size="10">']
    for q in range(8):
        o.append(f'<line x1="{x0}" y1="{Y(q):.1f}" x2="{x1}" y2="{Y(q):.1f}" stroke="#ccc"/>'
                 f'<text x="{x0 - 5}" y="{Y(q) + 3.5:.1f}" text-anchor="end">{q}</text>')
    for t in range(n):
        o.append(f'<line x1="{X(t):.1f}" y1="{y0}" x2="{X(t):.1f}" y2="{y1}" stroke="#bbb" stroke-dasharray="2,2"/>'
                 f'<text x="{X(t):.1f}" y="{y1 + 13}" text-anchor="middle">{t}</text>')
    # Catmull-Rom 曲線で標本点をなめらかにつなぐ（両端は少し延長）
    P = [(X(-0.5), Y(v[0] - (v[1] - v[0]) / 2))] + [(X(t), Y(u)) for t, u in enumerate(v)] + [(X(n - 0.5), Y(v[-1] + (v[-1] - v[-2]) / 2))]
    pts = []
    for i in range(1, len(P) - 2):
        p0, p1, p2, p3 = P[i - 1], P[i], P[i + 1], P[i + 2]
        for k in range(10):
            s = k / 10
            pts.append(tuple(0.5 * (2 * p1[j] + (-p0[j] + p2[j]) * s + (2 * p0[j] - 5 * p1[j] + 4 * p2[j] - p3[j]) * s ** 2
                                    + (-p0[j] + 3 * p1[j] - 3 * p2[j] + p3[j]) * s ** 3) for j in (0, 1)))
    pts.append(P[-2])
    o.append('<polyline fill="none" stroke="#0b5f84" stroke-width="1.4" points="' + " ".join(f"{a:.1f},{b:.1f}" for a, b in pts) + '"/>')
    for t, u in enumerate(v):
        x, y = X(t), Y(u)
        if t == 0:                                  # 右下（曲線は右上へ）
            dx, dy, an = 6, 12, "start"
        elif t == n - 1:                            # 右（曲線はここで終わる）
            dx, dy, an = 7, 4, "start"
        elif u >= v[t - 1] and u >= v[t + 1]:       # 山：真上
            dx, dy, an = 0, -7, "middle"
        elif u <= v[t - 1] and u <= v[t + 1]:       # 谷：右
            dx, dy, an = 8, 3, "start"
        elif v[t + 1] > u:                          # 上り：左上
            dx, dy, an = -6, -4, "end"
        else:                                       # 下り：右上
            dx, dy, an = 6, -4, "start"
        o.append(f'<circle cx="{x:.1f}" cy="{y:.1f}" r="3" fill="#000"/>'
                 f'<text x="{x + dx:.1f}" y="{y + dy:.1f}" text-anchor="{an}" font-size="9.5" stroke="#fff" stroke-width="3" paint-order="stroke">{u}</text>')
    o.append(f'<line x1="{x0}" y1="{y0}" x2="{x0}" y2="{y1}" stroke="#000"/><line x1="{x0}" y1="{y1}" x2="{x1}" y2="{y1}" stroke="#000"/>')
    o.append(f'<text x="{(x0 + x1) / 2}" y="{H - 3}" text-anchor="middle">標本の番号（一定の時間間隔）</text>')
    o.append("</svg>")
    return "".join(o)


