def fig_bar(vals=(("A店", 96), ("B店", 99)), lo=95, hi=100):
    W, H, x0, x1, y0, y1 = 270, 200, 48, 250, 26, 166
    Y = lambda v: y1 - (v - lo) / (hi - lo) * (y1 - y0)
    o = [f'<svg class="fig" width="{W}" height="{H}" viewBox="0 0 {W} {H}" xmlns="http://www.w3.org/2000/svg" font-size="11">',
         f'<text x="{(x0 + x1) / 2}" y="14" text-anchor="middle" font-size="12">顧客満足度（％）</text>']
    for v in range(lo, hi + 1):
        o.append(f'<line x1="{x0}" y1="{Y(v):.1f}" x2="{x1}" y2="{Y(v):.1f}" stroke="#ddd"/>'
                 f'<text x="{x0 - 5}" y="{Y(v) + 4:.1f}" text-anchor="end">{v}</text>')
    n = len(vals)
    bw = 52
    for k, (nm, v) in enumerate(vals):
        cx = x0 + (x1 - x0) * (k + 0.5) / n
        o.append(f'<rect x="{cx - bw / 2:.1f}" y="{Y(v):.1f}" width="{bw}" height="{y1 - Y(v):.1f}" fill="#3f8fb7" stroke="#000"/>'
                 f'<text x="{cx:.1f}" y="{y1 + 16}" text-anchor="middle">{nm}</text>')
    o.append(f'<line x1="{x0}" y1="{y0 - 6}" x2="{x0}" y2="{y1}" stroke="#000"/><line x1="{x0}" y1="{y1}" x2="{x1}" y2="{y1}" stroke="#000"/>')
    o.append("</svg>")
    return "".join(o), {nm: y1 - Y(v) for nm, v in vals}


