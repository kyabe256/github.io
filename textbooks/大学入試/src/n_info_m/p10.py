def with_parity(d):
    rows = [r + [sum(r) % 2] for r in d]
    rows.append([sum(rows[i][j] for i in range(len(d))) % 2 for j in range(len(d[0]))] + [None])
    return rows


def received():
    g = [r[:] for r in with_parity(DATA)]
    i, j = ERR
    g[i][j] ^= 1
    return g


def parity_table(g):
    head = ["", "1列目", "2列目", "3列目", "4列目", "パリティ"]
    rows = []
    for i, r in enumerate(g):
        lab = f"{i + 1}行目" if i < 4 else "パリティ"
        rows.append([lab] + [("" if v is None else str(v)) for v in r])
    return TB(head, rows)


