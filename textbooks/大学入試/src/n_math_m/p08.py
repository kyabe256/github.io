def verify():
    # A1
    assert gcd(252, 360) == 36 and 252*360//36 == 2520
    assert factorint(252) == {2: 2, 3: 2, 7: 1} and factorint(360) == {2: 3, 3: 2, 5: 1}
    assert gcd(1001, 357) == 7
    assert 1001 == 357*2+287 and 357 == 287+70 and 287 == 70*4+7 and 70 == 7*10
    # A2
    sols1 = {(x, y) for x in range(-60, 61) for y in range(-60, 61) if 7*x+11*y == 1}
    gen1 = {(11*k-3, -7*k+2) for k in range(-10, 11)}
    assert {s for s in sols1 if abs(s[0]) <= 50} == {s for s in gen1 if abs(s[0]) <= 50 and abs(s[1]) <= 60}
    assert 7*(-3)+11*2 == 1 and 11 == 7+4 and 7 == 4+3 and 4 == 3+1
    sols5 = {(x, y) for x in range(-60, 61) for y in range(-60, 61) if 7*x+11*y == 5}
    gen5 = {(11*k-4, -7*k+3) for k in range(-10, 11)}
    assert {s for s in sols5 if abs(s[0]) <= 50} == {s for s in gen5 if abs(s[0]) <= 50 and abs(s[1]) <= 60}
    # A3
    assert pow(3, 100, 7) == 4 and [pow(3, k, 7) for k in range(1, 7)] == [3, 2, 6, 4, 5, 1]
    assert pow(7, 2026, 10) == 9 and [pow(7, k, 10) for k in range(1, 5)] == [7, 9, 3, 1]
    # A4
    assert int("101101", 2) == 45 and 4*25 == 100 and Fr(1, 3)+Fr(2, 9) == Fr(5, 9)
    # B1
    from math import factorial
    f = factorial(50)
    e2 = 0
    while f % 2 == 0:
        f //= 2; e2 += 1
    assert e2 == 47
    s = str(factorial(50))
    assert len(s)-len(s.rstrip("0")) == 12
    # B2
    sol = sorted((x, y) for x in range(1, 200) for y in range(1, 200) if Fr(3, x)+Fr(2, y) == 1)
    assert sol == [(4, 8), (5, 5), (6, 4), (9, 3)]
    # B3
    assert all(n*n % 3 in (0, 1) for n in range(-50, 51))
    for a in range(1, 120):
        for b in range(a, 120):
            c2 = a*a+b*b; c = int(round(c2**0.5))
            if c*c == c2:
                assert a % 3 == 0 or b % 3 == 0
                assert a % 5 == 0 or b % 5 == 0 or c % 5 == 0
    assert sorted({n*n % 5 for n in range(5)}) == [0, 1, 4]
    # B4
    ns = [n for n in range(1, 1000) if n % 3 == 2 and n % 5 == 3 and n % 7 == 2]
    assert ns[0] == 23 and ns[-1] == 968 and all(n % 105 == 23 for n in ns)
    # B5
    assert all(gcd(n+3, 2*n+1) in (1, 5) for n in range(1, 2000))
    assert sum(1 for n in range(1, 101) if gcd(n+3, 2*n+1) == 5) == 20
    # C1
    assert all(n*n % 3 == 1 for n in range(-60, 61) if n % 3)
    assert [p for p in range(2, 3000) if isprime(p) and isprime(8*p*p+1)] == [3]
    assert [p for p in range(2, 400) if isprime(p) and isprime(p*p+2**p)] == [3]
    # C2
    sols = [(x, y, z) for x in range(1, 50) for y in range(1, 50) for z in range(1, 50)
            if Fr(1, x)+Fr(1, y)+Fr(1, z) == 1]
    assert sorted(s for s in sols if s[0] <= s[1] <= s[2]) == [(2, 3, 6), (2, 4, 4), (3, 3, 3)]
    assert len(sols) == 10
