    def med(a):
        a = sorted(a); n = len(a)
        return Fr(a[n//2]) if n % 2 else Fr(a[n//2-1]+a[n//2], 2)
    Q1, Q2, Q3 = med(d2[:5]), med(d2), med(d2[6:])
    assert (Q1, Q2, Q3) == (6, 10, 15)
    iqr = Q3-Q1
