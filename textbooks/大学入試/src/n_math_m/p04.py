    def mean(a): return Fr(sum(a), len(a))
    def cov(a, b): return mean([u*v for u, v in zip(a, b)]) - mean(a)*mean(b)
    S = [u+v for u, v in zip(X, Y)]
    assert cov(S, S) == cov(X, X)+2*cov(X, Y)+cov(Y, Y)
