def _divisors(n):
    return [d for d in range(1, n + 1) if n % d == 0]


def _lcm(a, b):
    return a * b // gcd(a, b)


def _vp(n, p):
    c = 0
    while n % p == 0:
        n //= p
        c += 1
    return c


def _isprime(n):
    if n < 2:
        return False
    if n % 2 == 0:
        return n == 2
    i = 3
    while i * i <= n:
        if n % i == 0:
            return False
        i += 2
    return True


def _to_base(n, b):
    s = ""
    while n:
        s = str(n % b) + s
        n //= b
    return s or "0"


