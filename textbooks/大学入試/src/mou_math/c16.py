def _walk(adj, start, N, stay=Fr(0), absorb=None):
    """グラフ上のランダムウォーク。各隣接頂点へ等確率（stay はとどまる確率）。
    戻り値：dist[n][v]（absorb を吸収点にしたときは未吸収の分布）と初到達確率 first[n]"""
    V = list(adj)
    cur = {v: Fr(int(v == start)) for v in V}
    dist, first = [dict(cur)], [Fr(0)]
    for _ in range(N):
        nxt = {v: Fr(0) for v in V}
        for v, pr in cur.items():
            if pr == 0: continue
            nxt[v] += pr*stay
            for w in adj[v]: nxt[w] += pr*(1 - stay)/len(adj[v])
        if absorb is not None:
            first.append(nxt[absorb]); nxt[absorb] = Fr(0)
        else:
            first.append(Fr(0))
        cur = nxt; dist.append(dict(cur))
    return dist, first


