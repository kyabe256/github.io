def _tilings(cells, shapes):
    """cells（(r,c) の集合）を shapes（相対座標の組の列。基準は最初のマス）で敷き詰める方法の数"""
    cells = frozenset(cells)
    memo = {}
    def go(rest):
        if not rest: return 1
        if rest in memo: return memo[rest]
        first = min(rest, key=lambda p: (p[1], p[0]))
        tot = 0
        for sh in shapes:
            pcs = {(first[0] + dr, first[1] + dc) for dr, dc in sh}
            if pcs <= rest: tot += go(rest - pcs)
        memo[rest] = tot
        return tot
    return go(cells)


