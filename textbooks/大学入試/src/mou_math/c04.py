def _merge(groups):
    """[(個数, 平均値, 分散), ...] → 合わせたデータの (平均値, 分散)"""
    N = sum(n for n, m, v in groups)
    S = sum(n * F(m) for n, m, v in groups)
    Q = sum(n * (F(v) + F(m) ** 2) for n, m, v in groups)
    return S / N, Q / N - (S / N) ** 2


