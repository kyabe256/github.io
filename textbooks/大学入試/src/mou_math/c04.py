def _rand_data(n, five, R):
    """5数要約が five に一致する整数データ（小さい順）を無作為に1つつくる"""
    mn, q1, q2, q3, mx = five
    h = n // 2

    def key(start, length, t):
        return ((start + length // 2,), t) if length % 2 else ((start + length // 2 - 1, start + length // 2), t)
    keys = [((0,), mn), key(0, h, q1), key(0, n, q2), key(n - h, h, q3), ((n - 1,), mx)]
    while True:
        x, lb, ok = [None] * n, mn, True
        for idx, t in keys:
            if len(idx) == 1:
                if t < lb:
                    ok = False
                    break
                x[idx[0]] = lb = t
            else:
                lo = max(lb, 2 * t - mx)
                if lo > t:
                    ok = False
                    break
                a = R.choice([lo, t, R.randint(lo, t)])
                x[idx[0]], x[idx[1]] = a, 2 * t - a
                lb = 2 * t - a
        if not ok:
            continue
        i = 0
        while i < n:                       # 未定の位置を、両隣の値の間の値で埋める
            if x[i] is None:
                j = i
                while x[j] is None:
                    j += 1
                vals = sorted(R.randint(x[i - 1], x[j]) for _ in range(j - i))
                x[i:j] = vals
                i = j
            i += 1
        if x == sorted(x) and _five(x) == tuple(F(v) for v in five):
            return x


