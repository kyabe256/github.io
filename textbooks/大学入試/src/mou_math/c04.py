# ---------------------------------------------------------------- 図の生成
def _px(v, lo, hi, x0, x1):
    return x0 + (v - lo) * (x1 - x0) / (hi - lo)


def _box_svg(rows, lo, hi, tick, lab, w=240, txt=None):
    """rows = [(名前, (最小, Q1, Q2, Q3, 最大)), ...] を共通の数直線上に描く箱ひげ図。
    tick ごとに薄い目盛り線、lab ごとに濃い線、txt ごとに数値（既定は lab ごと）"""
    txt = txt or lab
    left = 26 if any(nm for nm, _ in rows) else 10
    x0, x1 = left, w - 12
    rh, top = 30, 6
    ay = top + rh * len(rows) + 2
    h = ay + 16
    o = [f'<svg class="fig" width="{w}" height="{h}" viewBox="0 0 {w} {h}">']
    nt = round((hi - lo) / tick)
    for i in range(nt + 1):
        v = lo + i * tick
        X = _px(v, lo, hi, x0, x1)
        major = i % round(lab / tick) == 0
        o.append(f'<line x1="{X:.1f}" y1="{top}" x2="{X:.1f}" y2="{ay}" stroke="{"#b5b5b5" if major else "#e3e3e3"}" stroke-width="0.7"/>')
        if i % round(txt / tick) == 0:
            o.append(f'<text x="{X:.1f}" y="{ay + 12}" font-size="10" text-anchor="middle">{v:g}</text>')
    o.append(f'<line x1="{x0}" y1="{ay}" x2="{x1}" y2="{ay}" stroke="#333" stroke-width="1"/>')
    for i, (nm, (mn, q1, q2, q3, mx)) in enumerate(rows):
        cy = top + rh * i + rh / 2
        P = [_px(v, lo, hi, x0, x1) for v in (mn, q1, q2, q3, mx)]
        if nm:
            o.append(f'<text x="2" y="{cy + 4:.1f}" font-size="11">{nm}</text>')
        o.append(f'<line x1="{P[0]:.1f}" y1="{cy:.1f}" x2="{P[1]:.1f}" y2="{cy:.1f}" stroke="{_MAIN}" stroke-width="1.2"/>')
        o.append(f'<line x1="{P[3]:.1f}" y1="{cy:.1f}" x2="{P[4]:.1f}" y2="{cy:.1f}" stroke="{_MAIN}" stroke-width="1.2"/>')
        for X in (P[0], P[4]):
            o.append(f'<line x1="{X:.1f}" y1="{cy - 5:.1f}" x2="{X:.1f}" y2="{cy + 5:.1f}" stroke="{_MAIN}" stroke-width="1.2"/>')
        o.append(f'<rect x="{P[1]:.1f}" y="{cy - 8:.1f}" width="{P[3] - P[1]:.1f}" height="16" fill="{_SUB}" stroke="{_MAIN}" stroke-width="1.2"/>')
        o.append(f'<line x1="{P[2]:.1f}" y1="{cy - 8:.1f}" x2="{P[2]:.1f}" y2="{cy + 8:.1f}" stroke="{_MAIN}" stroke-width="2"/>')
    o.append('</svg>')
    return "".join(o)


def _scatter_svg(panels):
    """panels = [(ラベル, [(x, y), ...]), ...]  座標は 0〜100"""
    s, g = 74, 10
    w = len(panels) * s + (len(panels) - 1) * g + 8
    h = s + 22
    o = [f'<svg class="fig" width="{w}" height="{h}" viewBox="0 0 {w} {h}">']
    for i, (lb, pts) in enumerate(panels):
        ox, oy = 4 + i * (s + g), 4
        o.append(f'<rect x="{ox}" y="{oy}" width="{s}" height="{s}" fill="none" stroke="#555" stroke-width="0.9"/>')
        for (x, y) in pts:
            X, Y = ox + 3 + x * (s - 6) / 100, oy + s - 3 - y * (s - 6) / 100
            o.append(f'<circle cx="{X:.1f}" cy="{Y:.1f}" r="1.9" fill="{_MAIN}"/>')
        o.append(f'<text x="{ox + s / 2:.1f}" y="{oy + s + 14}" font-size="11" text-anchor="middle">{lb}</text>')
    o.append('</svg>')
    return "".join(o)


# ---------------------------------------------------------------- 検算用の関数
def _med(s):
    n = len(s)
    return F(s[n // 2]) if n % 2 else F(s[n // 2 - 1] + s[n // 2], 2)


def _five(d):
    """5数要約（日本の高校の定義）"""
    s = sorted(d)
    n, h = len(s), len(s) // 2
    return (F(s[0]), _med(s[:h]), _med(s), _med(s[n - h:]), F(s[-1]))


def _mean(d):
    return F(sum(F(x) for x in d), len(d))


def _var(d):
    m = _mean(d)
    return sum((F(x) - m) ** 2 for x in d) / len(d)


def _cov(x, y):
    mx, my = _mean(x), _mean(y)
    return sum((F(a) - mx) * (F(b) - my) for a, b in zip(x, y)) / len(x)


def _sqrtF(q):
    """Fraction の平方根が有理数ならそれを返す（そうでなければ None）"""
    q = F(q)
    a, b = math.isqrt(q.numerator), math.isqrt(q.denominator)
    return F(a, b) if a * a == q.numerator and b * b == q.denominator else None


def _corr(x, y):
    """相関係数（有理数になるときは Fraction、そうでなければ float）"""
    c = _cov(x, y)
    rt = _sqrtF(_var(x) * _var(y))
    return c / rt if rt is not None else float(c) / math.sqrt(float(_var(x) * _var(y)))


def _fcorr(x, y):
    n = len(x)
    mx, my = sum(x) / n, sum(y) / n
    sxy = sum((a - mx) * (b - my) for a, b in zip(x, y))
    return sxy / math.sqrt(sum((a - mx) ** 2 for a in x) * sum((b - my) ** 2 for b in y))


