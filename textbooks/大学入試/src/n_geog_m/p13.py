def _svg(w, h, body):
    return f'<svg class="fig" width="{w}" height="{h}" viewBox="0 0 {w} {h}">' + "".join(body) + "</svg>"


def _t(x, y, s, size=10, anchor="middle", col="#222"):
    return f'<text x="{x:.1f}" y="{y:.1f}" font-size="{size}" text-anchor="{anchor}" fill="{col}">{s}</text>'


def _ln(x1, y1, x2, y2, w=1.0, col="#222", dash=""):
    d = f' stroke-dasharray="{dash}"' if dash else ""
    return f'<line x1="{x1:.1f}" y1="{y1:.1f}" x2="{x2:.1f}" y2="{y2:.1f}" stroke="{col}" stroke-width="{w}"{d}/>'


def _rect(x, y, w, h, fill, stroke="#444", sw=0.6):
    return f'<rect x="{x:.1f}" y="{y:.1f}" width="{w:.1f}" height="{h:.1f}" fill="{fill}" stroke="{stroke}" stroke-width="{sw}"/>'


def stacked(rows, cats, cols, caption, unit="％", w=440):
    """100％帯グラフ。rows: [(ラベル, [値…])]。帯の長さは値に比例（座標は計算で決める）。"""
    L, R, T, H, G = 34, 12, 40, 22, 10
    W = w - L - R
    h = T + len(rows) * (H + G) + 30
    b = []
    x = L
    for c, col in zip(cats, cols):          # 凡例
        b.append(_rect(x, 10, 12, 10, col))
        b.append(_t(x + 16, 19, c, 9.5, "start"))
        x += 16 + 11 * len(c) + 22
    for k, (lab, vs) in enumerate(rows):
        y = T + k * (H + G)
        b.append(_t(L - 8, y + H / 2 + 4, lab, 11, "end"))
        x = L
        for v, col in zip(vs, cols):
            ww = W * v / 100
            if ww > 0:
                b.append(_rect(x, y, ww, H, col))
                if ww >= 20:
                    b.append(_t(x + ww / 2, y + H / 2 + 4, str(v), 9.5))
            x += ww
        assert abs(x - (L + W)) < 1e-6
    yb = T + len(rows) * (H + G) - G + 4
    for v in range(0, 101, 20):
        xx = L + W * v / 100
        b.append(_ln(xx, yb, xx, yb + 3, 0.8))
        b.append(_t(xx, yb + 14, f"{v}", 9))
    b.append(_t(L + W, yb + 26, unit, 9, "end"))
    return _svg(w, h, b) + f'<div style="text-align:center;font-size:9pt">{caption}</div>'


