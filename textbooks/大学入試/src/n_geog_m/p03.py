SUMMER_N = [3, 4, 5, 6, 7, 8]        # 4〜9月


def koppen(T, P, south=False):
    t, R = sum(T) / 12, sum(P)
    sm = [m for m in range(12) if (m in SUMMER_N) != south]
    wm = [m for m in range(12) if m not in sm]
    Ps = sum(P[m] for m in sm)
    x = 14 if Ps >= 0.7 * R else (0 if R - Ps >= 0.7 * R else 7)
    r = 20 * (t + x)
    if max(T) < 10:
        return "ET" if max(T) >= 0 else "EF"
    if R < r:
        return "BW" if R < r / 2 else "BS"
    if min(T) >= 18:
        return "Af" if min(P) >= 60 else "Aw/Am"
    s_min, w_max = min(P[m] for m in sm), max(P[m] for m in wm)
    w_min, s_max = min(P[m] for m in wm), max(P[m] for m in sm)
    if s_min < 30 and s_min < w_max / 3:
        lt = "s"
    elif w_min < s_max / 10:
        lt = "w"
    else:
        lt = "f"
    if min(T) >= -3:
        return "C" + lt + ("a" if max(T) >= 22 else "b")
    return "D" + lt


