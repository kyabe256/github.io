# ---- 図（座標はすべてここで計算する） ----
def _f(v):
    s = f"{v:.1f}"
    return s[:-2] if s.endswith(".0") else s


def _svg(w, h, body):
    return f'<svg class="fig" width="{w}" height="{h}" viewBox="0 0 {w} {h}">' + "".join(body) + "</svg>"


def _ln(x1, y1, x2, y2, c="#555", w=1.0, dash=None):
    d = f' stroke-dasharray="{dash}"' if dash else ""
    return f'<line x1="{_f(x1)}" y1="{_f(y1)}" x2="{_f(x2)}" y2="{_f(y2)}" stroke="{c}" stroke-width="{w}"{d}/>'


def _tx(x, y, s, size=10, anchor="middle", c="#222", bold=False):
    b = ' font-weight="bold"' if bold else ""
    return f'<text x="{_f(x)}" y="{_f(y)}" font-size="{size}" text-anchor="{anchor}" fill="{c}"{b}>{s}</text>'


def _pl(pts, c="#333", w=1.0, fill="none", close=False, dash=None):
    p = " ".join(f"{_f(x)},{_f(y)}" for x, y in pts)
    tag = "polygon" if close else "polyline"
    d = f' stroke-dasharray="{dash}"' if dash else ""
    return f'<{tag} points="{p}" fill="{fill}" stroke="{c}" stroke-width="{w}"{d}/>'


def _rect(x, y, w, h, fill, stroke="none", sw=0.6):
    return f'<rect x="{_f(x)}" y="{_f(y)}" width="{_f(w)}" height="{_f(h)}" fill="{fill}" stroke="{stroke}" stroke-width="{sw}"/>'


def _dot(x, y, r=1.8, c="#c0392b"):
    return f'<circle cx="{_f(x)}" cy="{_f(y)}" r="{_f(r)}" fill="{c}"/>'


def _climo(ox, oy, T, P, title, tmin=-30, tmax=40, pmax=350, W=150, H=130):
    """雨温図：左目盛り＝気温（折れ線）、右目盛り＝降水量（棒）。気温 10℃ と降水量 pmax/目盛り数 を対応させる"""
    nt = (tmax - tmin) // 10
    assert pmax % nt == 0
    ps = pmax // nt
    yT = lambda t: oy + H - (t - tmin) / (tmax - tmin) * H
    bw = W / 12
    out = []
    for k in range(nt + 1):
        y = oy + H - k * H / nt
        out.append(_ln(ox, y, ox + W, y, "#ddd", 0.6))
        out.append(_tx(ox - 3, y + 3.5, f"{tmin + 10 * k}", 9, "end"))
        out.append(_tx(ox + W + 3, y + 3.5, f"{k * ps}", 9, "start"))
    for m in range(12):
        h = P[m] / pmax * H
        out.append(_rect(ox + m * bw + bw * 0.15, oy + H - h, bw * 0.7, h, "#8fbce6", "#4a86c5"))
        if m in (0, 6, 11):
            out.append(_tx(ox + (m + 0.5) * bw, oy + H + 11, f"{m + 1}", 9))
    out += [_ln(ox, oy, ox, oy + H, "#555"), _ln(ox + W, oy, ox + W, oy + H, "#555"), _ln(ox, oy + H, ox + W, oy + H, "#555")]
    if tmin < 0 < tmax:
        out.append(_ln(ox, yT(0), ox + W, yT(0), "#999", 0.8))
    pts = [(ox + (m + 0.5) * bw, yT(T[m])) for m in range(12)]
    out.append(_pl(pts, "#c0392b", 1.6))
    out += [_dot(x, y) for x, y in pts]
    out += [_tx(ox - 3, oy - 5, "℃", 9, "end"), _tx(ox + W + 3, oy - 5, "mm", 9, "start"),
            _tx(ox + W / 2, oy - 7, title, 12, bold=True), _tx(ox + W / 2, oy + H + 23, "（月）", 9)]
    return out


def _hyther(ox, oy, series, W=280, H=170, pmax=250, tmax=30):
    X = lambda p: ox + p / pmax * W
    Y = lambda t: oy + H - t / tmax * H
    out = []
    for p in range(0, pmax + 1, 50):
        out += [_ln(X(p), oy, X(p), oy + H, "#e2e2e2", 0.6), _tx(X(p), oy + H + 12, f"{p}", 9)]
    for t in range(0, tmax + 1, 5):
        out += [_ln(ox, Y(t), ox + W, Y(t), "#e2e2e2", 0.6), _tx(ox - 4, Y(t) + 3.5, f"{t}", 9, "end")]
    out += [_ln(ox, oy, ox, oy + H, "#555"), _ln(ox, oy + H, ox + W, oy + H, "#555"),
            _tx(ox + W / 2, oy + H + 26, "月降水量（mm）", 10), _tx(ox - 4, oy - 7, "気温（℃）", 10, "start")]
    for name, T, P, col, dash, lab, mpos in series:
        pts = [(X(P[m]), Y(T[m])) for m in range(12)]
        out.append(_pl(pts + [pts[0]], col, 1.5, dash=dash))
        for m, (x, y) in enumerate(pts):
            out.append(_dot(x, y, 2.1, col))
            if m in (0, 6):
                dx, dy, anc = mpos[m // 6]
                out.append(_tx(x + dx, y + dy, f"{m + 1}月", 9, anc, col))
        out.append(_tx(X(lab[0]), Y(lab[1]), name, 13, c=col, bold=True))
    return out


