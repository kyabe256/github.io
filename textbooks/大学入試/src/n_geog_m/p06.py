def _svg(w, h, body):
    return f'<svg class="fig" width="{w}" height="{h}" viewBox="0 0 {w} {h}">' + "".join(body) + "</svg>"


def _ln(x1, y1, x2, y2, c="#555", w=1.0, dash=None):
    d = f' stroke-dasharray="{dash}"' if dash else ""
    return f'<line x1="{_f(x1)}" y1="{_f(y1)}" x2="{_f(x2)}" y2="{_f(y2)}" stroke="{c}" stroke-width="{w}"{d}/>'


def _tx(x, y, s, size=10, anchor="middle", c="#222", bold=False):
    b = ' font-weight="bold"' if bold else ""
    return f'<text x="{_f(x)}" y="{_f(y)}" font-size="{size}" text-anchor="{anchor}" fill="{c}"{b}>{s}</text>'


def _circ(x, y, r, fill, stroke="#333"):
    return f'<circle cx="{_f(x)}" cy="{_f(y)}" r="{_f(r)}" fill="{fill}" stroke="{stroke}" stroke-width="1"/>'


