def _inside(pt, poly):
    x, y = pt
    c = False
    for (x1, y1), (x2, y2) in zip(poly, poly[1:] + poly[:1]):
        if (y1 > y) != (y2 > y) and x < x1 + (y - y1) * (x2 - x1) / (y2 - y1):
            c = not c
    return c


def zone(pt):
    """図の上で、点がどの区域にあるか"""
    x, y = pt
    if _inside(pt, PLATEAU):
        return "none"
    if RIVER[0] <= y < RIVER[1]:
        return "river"
    if LEVEE_N[0] <= y < LEVEE_N[1] or LEVEE_S[0] <= y < LEVEE_S[1]:
        return "low"
    if _inside(pt, DEEP):
        return "3m"
    return "mid"


