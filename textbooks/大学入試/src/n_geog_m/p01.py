UTC = {"東京": 9, "ロンドン": 0, "ロサンゼルス": -8, "ニューヨーク": -5}


def _shift(day, hour, frm, to):
    """day 日 hour 時（frm の標準時）を to の標準時に直す → (日, 時)"""
    t = day * 24 + hour - UTC[frm] + UTC[to]
    return t // 24, t % 24


def _tokyo_east_landfall():
    """東京（北緯35.7°、東経139.7°）から真東（方位角90°）へ進む大圏の、出発後 16000〜18000 km の位置"""
    lat0, lon0, az = math.radians(35.7), math.radians(139.7), math.radians(90)
    out = []
    for dkm in (6000, 10000, 16000, 17000, 18000):
        d = dkm / 6371
        lat = math.asin(math.sin(lat0) * math.cos(d) + math.cos(lat0) * math.sin(d) * math.cos(az))
        lon = lon0 + math.atan2(math.sin(az) * math.sin(d) * math.cos(lat0), math.cos(d) - math.sin(lat0) * math.sin(lat))
        out.append((dkm, math.degrees(lat), (math.degrees(lon) + 180) % 360 - 180))
    return out


