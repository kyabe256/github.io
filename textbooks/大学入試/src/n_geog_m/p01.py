def _base_y(h):
    k = (h - 100) // 10
    return 200 - 18 * k if k <= 5 else 110 - 9 * (k - 5)


def _bend(x):
    # 谷では等高線が高い側（北＝上）へ、尾根では低い側（南＝下）へ張り出す
    return -BEND * math.exp(-((x - VAL_X) / WID) ** 2) + BEND * math.exp(-((x - RID_X) / WID) ** 2)


def _cy(h, x):
    return _base_y(h) + _bend(x)


