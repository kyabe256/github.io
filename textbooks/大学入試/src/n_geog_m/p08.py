def _smooth(u):
    u = min(max(u, 0.0), 1.0)
    return u * u * (3 - 2 * u)


def birth(s):
    if s < 2:
        return 39.0
    if s < 3:
        return 39 - 26 * _smooth(s - 2)
    return 13 - (s - 3)


def death(s):
    if s < 1:
        return 36 + 2 * math.sin(6 * math.pi * s)
    if s < 2:
        return 36 - 22 * _smooth(s - 1)
    if s < 3:
        return 14 - 4 * _smooth(s - 2)
    return 10 + 0.5 * (s - 3)


