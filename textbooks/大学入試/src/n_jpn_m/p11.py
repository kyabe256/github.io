        assert it["lv"] in ("A", "B", "C") and it["tag"] and it["q"].strip() and it["a"].strip() and it["s"].strip(), i
        whole = it["q"] + it["a"] + it["s"]
        assert "$" not in whole, i
        for t in ("div", "u", "b", "sub", "sup", "table", "tr", "td", "th"):
            assert len(re.findall(f"<{t}[ >]", whole)) == whole.count(f"</{t}>"), (i, t)
        assert "<b>ポイント</b>" in it["s"], i
        if "選択" in it["tag"]:
            assert re.fullmatch("[①②③④⑤]", it["a"]) and it["a"] in it["q"], (i, it["a"])
        lim = re.findall(r"(\d+)字以内", it["q"])
        ex = re.findall(r"解答例：(.*?)（(\d+)字）", it["a"] + it["s"])
        for body, n in ex:
            assert len(body) == int(n), (i, len(body), n)
            if lim:
                assert len(body) <= int(lim[-1]), (i, len(body), lim)
        if lim:
            assert ex, (i, "解答例がない")
