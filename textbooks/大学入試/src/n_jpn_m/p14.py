        if "選択" in it["tag"]:
            assert re.fullmatch("[①②③④⑤]", it["a"]) and it["a"] in it["q"], (i, it["a"])
        lim = re.findall(r"(\d+)字以内", it["q"])
        ex = re.findall(r"解答例：(.*?)（(\d+)字）", it["a"] + it["s"])
        for body, n in ex:
            assert len(body) == int(n), (i, len(body), n)
            if lim:
                assert len(body) <= int(lim[-1]), (i, len(body), lim)
        if lim:
            assert ex, (i, "解答例がない")
