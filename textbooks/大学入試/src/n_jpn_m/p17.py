import re

def _hira(s):
    return "".join(chr(ord(c) - 0x60) if "ァ" <= c <= "ヶ" else c for c in s)

_NUM = {"一": 1, "二": 2, "三": 3, "四": 4}
_UL = {"上": 1, "中": 2, "下": 3}
_SEP = set("、。　，\n")

def _tokens(html):
    toks, i = [], 0
    while i < len(html):
        for tag, key in (("<sup>", "ok"), ("<sub>", "mk")):
            if html.startswith(tag, i):
                j = html.index("</" + tag[1:], i)
                toks[-1][key] += html[i + len(tag):j]
                i = j + len(tag) + 1
                break
        else:
            if html.startswith("<br>", i):
                toks.append({"c": "\n", "ok": "", "mk": ""}); i += 4
            elif html[i] == "<":
                i = html.index(">", i) + 1
            elif html[i] == "（":          # 傍線部の記号（ア）などは読まない
                i = html.index("）", i) + 1
            else:
                toks.append({"c": html[i], "ok": "", "mk": ""}); i += 1
    return toks

def _marks(t):
    mk = t["mk"]
    return ("レ" in mk, next((_NUM[c] for c in mk if c in _NUM), 0), next((_UL[c] for c in mk if c in _UL), 0))

def _order(seg, saidoku):
    out, pend = [], set()
    def read(i):
        out.append((i, any(o == i for o, _ in out)))
        pend.discard(i)
        r, n, u = _marks(seg[i])
        if n:
            c = [k for k in pend if k < i and _marks(seg[k])[1] == n + 1]
            if c:
                read(max(c))
        if u:
            for v in ((2, 3) if u == 1 else (3,) if u == 2 else ()):
                c = [k for k in pend if k < i and _marks(seg[k])[2] == v]
                if c:
                    read(max(c)); break
        if i - 1 in pend and _marks(seg[i - 1])[0]:
            read(i - 1)
    for i, t in enumerate(seg):
        r, n, u = _marks(t)
        if t["c"] in saidoku:
            out.append((i, False)); pend.add(i)
        elif r or n >= 2 or u >= 2:
            pend.add(i)
        else:
            read(i)
    assert not pend, ("読まれない字", [seg[k]["c"] for k in pend])
    return out

def kudashi(html, kana=None, oki="", saidoku=None):
    """kana: {字: 読み} または {(字, 何番目): 読み}。読みが None なら漢字のまま。不・弗は送り仮名から ず／ざ を決める。
    oki: 読まない置き字。saidoku: {字: [二度目の読み, ...]}（出てくる順）"""
    kana = dict(kana or {})
    saidoku = {k: list(v) for k, v in (saidoku or {}).items()}
    toks = _tokens(html)
    seen = {}
    for t in toks:
        seen[t["c"]] = seen.get(t["c"], -1) + 1
        t["n"] = seen[t["c"]]
    res, seg = [], []
    def flush():
        for i, second in _order(seg, saidoku):
            t = seg[i]; c = t["c"]
            if second:
                res.append(saidoku[c].pop(0)); continue
            k = kana.get((c, t["n"]), kana.get(c, "?"))
            if k == "?":
                if c in oki and not t["ok"]:
                    k = ""
                elif c in "不弗":
                    k = "ざ" if t["ok"][:1] and t["ok"][0] in "ラリルレ" else "ず"
                else:
                    k = c
            res.append((c if k is None else k) + _hira(t["ok"]))
        seg.clear()
    for t in toks:
        if t["c"] in _SEP:
            flush(); res.append(t["c"])
        else:
            seg.append(t)
    flush()
    assert all(not v for v in saidoku.values()), saidoku
    return "".join(res)

def bare(html):
    """返り点・送り仮名・タグ・傍線記号を除いた白文"""
    s = re.sub(r"<sup>.*?</sup>|<sub>.*?</sub>|（.*?）", "", html.replace("<br>", "\n"))
    return re.sub(r"<[^>]+>", "", s)

