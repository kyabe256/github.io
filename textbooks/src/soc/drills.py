def dhondt(votes, seats):
    q = []
    for p, v in votes.items():
        for d in range(1, seats + 2):
            q.append((F(v, d), p))
    q.sort(reverse=True)
    assert q[seats - 1][0] != q[seats][0]  # 同数で決まらない問題は使わない
    res = {p: 0 for p in votes}
    for _, p in q[:seats]:
        res[p] += 1
    return res

def dhondt_items(n):
    items = []
