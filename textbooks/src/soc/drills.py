# ---------- 時差 ----------
CITIES = [("ロンドン", 0), ("パリ", 15), ("カイロ", 30), ("モスクワ", 45), ("バンコク", 105),
          ("ペキン", 120), ("シドニー", 150), ("ニューヨーク", -75), ("シカゴ", -90),
          ("ロサンゼルス", -120), ("ホノルル", -150)]
def lon(d):
    return f"東経{d}度" if d > 0 else ("経度0度" if d == 0 else f"西経{-d}度")
def hm(t):
    h = t.hour
    if h == 0: s = "午前0時"
    elif h < 12: s = f"午前{h}時"
    elif h == 12: s = "正午"
    else: s = f"午後{h-12}時"
    return f"{t.month}月{t.day}日{s}"
def jisa_items(n):
    items = []
    used = set()
    while len(items) < n:
        c, L = random.choice(CITIES)
        if c in used: continue
        used.add(c)
        t = datetime.datetime(2026, random.choice([1, 3, 7, 12]), random.randint(1, 28), random.randint(0, 23))
        if t.hour in (0, 12): continue
        diff = (135 - L) // 15
        assert (135 - L) % 15 == 0
        u = t - datetime.timedelta(hours=diff)
        q = f"東京（東経135度）が{hm(t)}のとき、{c}（標準時子午線{lon(L)}）は何月何日の何時？"
        a = f"時差{abs(diff)}時間（{c}が{'遅れ' if diff > 0 else '進み'}）→ {hm(u)}"
        items.append((q, a))
    return items

