def fmt(x, unit=""):
    x = F(x)
    if x.denominator == 1:
        s = str(x.numerator)
    else:
        s = f"{float(x):.4f}".rstrip("0").rstrip(".")
        assert F(s) == x, (x, s)  # 割り切れる値だけを許す
    return s + unit

