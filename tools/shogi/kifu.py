"""定跡手順の登録と検証。

手順はすべて USI 形式で書き、エンジンで合法性を確認したうえで
日本語表記と局面図を機械的に生成する。図面と手順が食い違うことがない。
"""

from __future__ import annotations

import shogi
from shogi import Position, move_str, CH_SFEN, PROMOTE, ptype

HIRATE = "lnsgkgsnl/1r5b1/ppppppppp/9/9/9/PPPPPPPPP/1B5R1/LNSGKGSNL b - 1"


def parse_usi(pos: Position, s: str):
    if s[1] == "*":
        t = CH_SFEN[s[0]]
        c = 9 - int(s[2])
        r = ord(s[3]) - ord("a")
        return ("d", t, r, c)
    fc = 9 - int(s[0])
    fr = ord(s[1]) - ord("a")
    tc = 9 - int(s[2])
    tr = ord(s[3]) - ord("a")
    pro = s.endswith("+")
    return ("m", fr, fc, tr, tc, pro)


def play(moves, start=HIRATE):
    """手順を再生し、(局面, 手) の列と最終局面を返す。不正手は例外。"""
    pos = Position.from_sfen(start)
    seq = []
    for n, u in enumerate(moves, 1):
        mv = parse_usi(pos, u)
        legal = pos.legal_moves()
        if mv not in legal:
            raise ValueError("%d手目 %s は不正手 (局面 %s)" % (n, u, pos.to_sfen()))
        seq.append((pos, mv))
        pos = pos.do(mv)
    return seq, pos


def notation(seq):
    out, prev = [], None
    for pos, mv in seq:
        out.append(move_str(pos, mv, prev))
        prev = (mv[2], mv[3]) if mv[0] == "d" else (mv[3], mv[4])
    return out


